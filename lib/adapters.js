// ---------------- LIBSYN (podcast host) ----------------
async function libsynVerifyLive(ep) {
  // No API needed for the live check — the public episode/website URL tells the truth.
  const url = ep.liveUrl || ep.link || `https://www.thrivingdentist.com/?s=${encodeURIComponent(ep.title)}`;
  try {
    const res = await fetch(url, { method: "GET", redirect: "follow" });
    return { live: res.ok, status: res.status, url, checked: "public URL" };
  } catch (err) {
    return { live: false, status: 0, url, error: err.message, checked: "public URL" };
  }
}


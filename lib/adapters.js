// ---------------- AI WRITING (Anthropic preferred, OpenAI fallback) ----------------
async function aiGenerate(system, user, maxTokens) {
  if (aiProvider === "Anthropic") {
    const res = await fetch("https://api.anthropic.com/v1/messages", {
      method: "POST",
      headers: {
        "x-api-key": cfg.ANTHROPIC_API_KEY,
        "anthropic-version": "2023-06-01",
        "content-type": "application/json",
      },
      body: JSON.stringify({
        model: cfg.ANTHROPIC_MODEL,
        max_tokens: maxTokens || 4000,
        system,
        messages: [{ role: "user", content: user }],
      }),
    });
    if (!res.ok) throw new Error("Anthropic API " + res.status + ": " + (await res.text()));
    const data = await res.json();
    return data.content.map((c) => c.text || "").join("\n");
  }
  if (aiProvider === "OpenAI") {
    const res = await fetch("https://api.openai.com/v1/chat/completions", {
      method: "POST",
      headers: {
        authorization: "Bearer " + cfg.OPENAI_API_KEY,
        "content-type": "application/json",
      },
      body: JSON.stringify({
        model: cfg.OPENAI_MODEL,
        max_tokens: maxTokens || 4000,
        messages: [
          { role: "system", content: system },
          { role: "user", content: user },
        ],
      }),
    });
    if (!res.ok) throw new Error("OpenAI API " + res.status + ": " + (await res.text()));
    const data = await res.json();
    return data.choices[0].message.content;
  }
  // MOCK: deterministic sample output so the pipeline is fully demonstrable
  return null; // callers provide their own mock builder
}


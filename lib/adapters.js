// ---------------- KIT (email platform) ----------------
async function kitScheduleBroadcast(ep, kind, html, sendAt) {
  let subject = (html.match(/^SUBJECT:\s*(.+)$/m) || [])[1] || `TD EP ${ep.ep} — ${kind}`;
  // Safety prefix: forces a conscious human edit inside Kit before any send.
  subject = '[REVIEW BEFORE SEND] ' + subject;
  const htmlBody = html.slice(html.indexOf("<"));
  try {
    if (cfg.KIT_API_KEY) {
      // Kit v4: create a broadcast (draft) with scheduled send time.
      // DRAFT ONLY — no send_at, ever. The system never sends or schedules an
      // email by itself; a human sets the audience and schedules inside Kit.
      const res = await kfetch("https://api.kit.com/v4/broadcasts", {
        method: "POST",
        headers: { "X-Kit-Api-Key": cfg.KIT_API_KEY, "content-type": "application/json" },
        body: JSON.stringify({ subject, content: htmlBody }),
      });
      if (!res.ok) throw new Error("Kit v4 " + res.status + ": " + (await res.text()).slice(0, 200));
      const data = await res.json();
      return { id: data.broadcast?.id || "kit-v4", sendAt };
    }
    if (cfg.KIT_API_SECRET) {
      // Kit v3: create broadcast as a DRAFT (public:false, no send_at) so a human
      // confirms audience filters (TD tags + exclude Cold Subscribers) in Kit
      // before it is scheduled — per the Kit SOP.
      const res = await kfetch("https://api.convertkit.com/v3/broadcasts", {
        method: "POST",
        headers: { "content-type": "application/json" },
        body: JSON.stringify({ api_secret: cfg.KIT_API_SECRET, subject, content: htmlBody, public: false }),
      });
      if (!res.ok) throw new Error("Kit v3 " + res.status + ": " + (await res.text()).slice(0, 200));
      const data = await res.json();
      return { id: data.broadcast?.id || "kit-v3-draft", sendAt, draft: true, note: "Created as DRAFT in Kit — set audience (TD tags, exclude Cold Subscribers) and schedule inside Kit." };
    }
    if (cfg.KIT_API_V3_KEY) {
      return { id: "PENDING-NEEDS-SECRET", sendAt, note: "v3 API Key connected (read-only). Add KIT_API_SECRET in config.js to create the broadcast in Kit automatically." };
    }
  } catch (err) {
    return { id: "KIT-ERROR", sendAt, error: err.message };
  }
  return { id: "mock-kit-" + kind + "-" + ep.ep, sendAt, mock: true };
}

